/*
  Builds supabase/setup.sql: the whole database setup as one script that can
  be pasted into Supabase's SQL Editor and run once on an empty project.
  It is generated from the same sources the migrate command uses (Better
  Auth's schema plus server/db/migrations), so the two never drift; a test
  checks the committed file is current and that it matches `npm run migrate`.

  Usage: npm run db:sql   (needs a local PostgreSQL; see SQLCHECK_DATABASE_URL)
*/
import { readdirSync, readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { getMigrations } from 'better-auth/db/migration'
import type pg from 'pg'
import { authOptions } from '../auth.js'

const here = dirname(fileURLToPath(import.meta.url))
export const SQLCHECK_DATABASE_URL = process.env.SQLCHECK_DATABASE_URL ?? 'postgres://nurselove:nurselove-local@localhost:5432/nurselove_sqlcheck'

/** Supabase's free plan caps stored files at 50 MB; the buckets match the app's defaults. */
const BUCKET_LIMIT_BYTES = 50 * 1024 * 1024

/** Empties the public schema of a scratch database. Never point this at a real one. */
export async function resetScratchDatabase(pool: pg.Pool) {
  const db = (await pool.query<{ db: string }>('select current_database() as db')).rows[0].db
  if (!db.includes('sqlcheck')) throw new Error(`Refusing to reset ${db}: only a scratch database named *sqlcheck* may be reset.`)
  await pool.query('drop schema if exists public cascade; create schema public;')
}

/** The full setup script. `pool` must point at an EMPTY scratch database. */
export async function buildSetupSql(pool: pg.Pool) {
  const { compileMigrations } = await getMigrations(authOptions(pool) as never)
  const authSql = (await compileMigrations()).trim()
  const files = readdirSync(join(here, 'migrations')).filter((f) => f.endsWith('.sql')).sort()
  const store = files.map((f) => `-- ${f}\n${readFileSync(join(here, 'migrations', f), 'utf8').trim()}\ninsert into schema_migrations (name) values ('${f}');`).join('\n\n')
  return `-- Nurse Love Company: complete database setup for Supabase.
--
-- How to use: Supabase dashboard, SQL Editor, New query. Paste this whole
-- file, click Run, and wait for "Success". Run it ONCE on a new, empty
-- project. If the store's tables already exist it stops without changing
-- anything.
--
-- Generated by \`npm run db:sql\` from server/db/migrations. Do not edit by
-- hand. Everything runs in one transaction: it either all applies or none
-- of it does.

begin;

do $$ begin
  if to_regclass('public.schema_migrations') is not null then
    raise exception 'This database is already set up (schema_migrations exists). Nothing was changed.';
  end if;
end $$;

-- 1. Accounts and sign in sessions (Better Auth)
${authSql}

-- 2. The store
create table if not exists schema_migrations (name text primary key, applied_at timestamptz not null default now());

${store}

-- 3. Row level security on every store table. The store's server is the
-- table owner and is unaffected; Supabase's public Data API sees nothing.
do $$ declare t record; begin
  for t in select tablename from pg_tables where schemaname = 'public' and not rowsecurity loop
    execute format('alter table public.%I enable row level security', t.tablename);
  end loop;
end $$;

-- 4. Two PRIVATE storage buckets: purchasable files, and media (photos,
-- sample pages, tutorial videos). Skipped outside Supabase.
do $$ begin
  if exists (select 1 from pg_namespace where nspname = 'storage') then
    insert into storage.buckets (id, name, public, file_size_limit)
    values ('product-files', 'product-files', false, ${BUCKET_LIMIT_BYTES}), ('media', 'media', false, ${BUCKET_LIMIT_BYTES})
    on conflict (id) do update set public = false, file_size_limit = excluded.file_size_limit;
  end if;
end $$;

commit;
`
}
